/** Stored edits override defaults section by section, so new sections always have content. */
export function mergeContent(stored: unknown): LoveContent {
  if (!stored || typeof stored !== "object") return DEFAULT_CONTENT;
  const s = stored as Partial<LoveContent>;
  return {
    opening: { ...DEFAULT_CONTENT.opening, ...(s.opening ?? {}) },
    memoriesIntro: s.memoriesIntro ?? DEFAULT_CONTENT.memoriesIntro,
    story: Array.isArray(s.story) && s.story.length === 10 ? s.story : DEFAULT_CONTENT.story,
    questions: { ...DEFAULT_CONTENT.questions, ...(s.questions ?? {}) },
    quiz: Array.isArray(s.quiz) && s.quiz.length > 0 ? s.quiz : DEFAULT_CONTENT.quiz,
    puzzle: { ...DEFAULT_CONTENT.puzzle, ...(s.puzzle ?? {}) },
    reasons: Array.isArray(s.reasons) && s.reasons.length > 0 ? s.reasons : DEFAULT_CONTENT.reasons,
    timeline: Array.isArray(s.timeline) ? s.timeline : DEFAULT_CONTENT.timeline,
    letter: { ...DEFAULT_CONTENT.letter, ...(s.letter ?? {}) },
    finale: { ...DEFAULT_CONTENT.finale, ...(s.finale ?? {}) },
  };
}
